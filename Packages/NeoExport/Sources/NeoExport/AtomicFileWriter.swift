import Foundation
import NeoCore

/// A POSIX file operation failed.
struct POSIXFileError: Error, Hashable {
    /// The operation that failed, such as `open` or `rename`.
    let operation: String

    /// The path the operation ran on.
    let path: String

    /// The `errno` value the operation reported.
    let code: Int32

    /// A message that names the operation, the path, and the reason.
    var message: String {
        "\(operation) failed on \(path): \(String(cString: strerror(code)))"
    }
}

/// The small set of file operations the publisher needs.
///
/// Foundation is the only import, because it re-exports the platform C library on
/// both macOS and Linux. Using `open`/`write`/`fsync`/`rename` directly is what
/// makes the staged write durable and the replacement atomic: a rename over an
/// existing path either happens or does not, so a reader never sees a partial
/// file.
enum POSIXFileSystem {
    /// Writes bytes to a path, flushing them to the device before returning.
    static func writeFile(_ bytes: [UInt8], to path: String) throws {
        let descriptor = open(path, O_WRONLY | O_CREAT | O_TRUNC, 0o644)
        guard descriptor >= 0 else {
            throw POSIXFileError(operation: "open", path: path, code: errno)
        }
        defer { close(descriptor) }

        var offset = 0
        while offset < bytes.count {
            let written = bytes.withUnsafeBufferPointer { buffer in
                write(descriptor, buffer.baseAddress! + offset, buffer.count - offset)
            }
            guard written > 0 else {
                throw POSIXFileError(operation: "write", path: path, code: errno)
            }
            offset += written
        }

        guard fsync(descriptor) == 0 else {
            throw POSIXFileError(operation: "fsync", path: path, code: errno)
        }
    }

    /// Reads a file's bytes.
    static func readFile(at path: String) throws -> [UInt8] {
        let descriptor = open(path, O_RDONLY)
        guard descriptor >= 0 else {
            throw POSIXFileError(operation: "open", path: path, code: errno)
        }
        defer { close(descriptor) }

        var bytes: [UInt8] = []
        var buffer = [UInt8](repeating: 0, count: 16 * 1024)
        while true {
            let count = buffer.withUnsafeMutableBufferPointer { pointer in
                read(descriptor, pointer.baseAddress, pointer.count)
            }
            guard count >= 0 else {
                throw POSIXFileError(operation: "read", path: path, code: errno)
            }
            if count == 0 { break }
            bytes.append(contentsOf: buffer[..<count])
        }
        return bytes
    }

    /// Renames one path onto another, replacing the destination atomically.
    static func replaceFile(at path: String, with staged: String) throws {
        guard rename(staged, path) == 0 else {
            throw POSIXFileError(operation: "rename", path: path, code: errno)
        }
    }

    /// Removes a path, ignoring a path that does not exist.
    static func removeFile(at path: String) {
        _ = unlink(path)
    }
}

/// Publishes one target file safely: stage a sibling temporary file, verify it,
/// preserve the previous bytes, then rename the staged file into place.
struct AtomicFileWriter {
    /// The file manager used for directory listings and moves.
    let fileManager: FileManager

    /// How many prior versions of a target are kept.
    let backupDepth: Int

    /// Publishes bytes to a target path.
    ///
    /// - Parameters:
    ///   - bytes: The generated bytes.
    ///   - target: The destination file URL.
    /// - Returns: `unchanged` when the target already holds the bytes,
    ///   `published` when the target now holds them, and `failed` with a reason
    ///   when the target was left as it was.
    func publish(bytes: [UInt8], to target: URL) -> PenExportFileStatus {
        let path = target.path

        if let reason = symlinkRefusal(path) {
            return .failed(reason: reason)
        }

        let existing: [UInt8]?
        do {
            existing = try readIfPresent(path)
        } catch {
            return .failed(reason: "the existing file could not be read: \(describe(error))")
        }

        if let existing, existing == bytes {
            // The target already holds exactly these bytes, so it is left alone
            // and no backup is created.
            return .unchanged
        }

        // A retry removes what an interrupted run left behind, so orphaned
        // temporary files cannot accumulate.
        removeOrphanTemps(for: path)

        if let existing, let reason = preserve(existing, for: path) {
            return .failed(reason: reason)
        }

        if let reason = stageAndReplace(bytes, path: path) {
            return .failed(reason: reason)
        }

        return .published
    }

    /// A reason to refuse a target or one of its backup slots.
    ///
    /// A symlink is never followed: a target that is a link would otherwise let
    /// an export write outside the folder the user chose.
    private func symlinkRefusal(_ path: String) -> String? {
        for candidate in [path] + (1...max(1, backupDepth)).map({ "\(path).bak\($0)" })
        where isSymlink(candidate) {
            return "\(candidate) is a symbolic link, which this build does not follow"
        }
        return nil
    }

    /// Whether a path is a symbolic link.
    private func isSymlink(_ path: String) -> Bool {
        (try? fileManager.destinationOfSymbolicLink(atPath: path)) != nil
    }

    /// The target's bytes, or `nil` when the target does not exist.
    private func readIfPresent(_ path: String) throws -> [UInt8]? {
        guard fileManager.fileExists(atPath: path) else { return nil }
        return try POSIXFileSystem.readFile(at: path)
    }

    /// Moves the previous bytes into the target's backup history.
    ///
    /// The prior version is staged and verified before any slot is touched, so a
    /// failure here leaves the target exactly as it was.
    private func preserve(_ bytes: [UInt8], for path: String) -> String? {
        let stagedBackup = "\(path).bak-tmp-\(UUID().uuidString)"
        do {
            try POSIXFileSystem.writeFile(bytes, to: stagedBackup)
            let staged = try POSIXFileSystem.readFile(at: stagedBackup)
            guard staged == bytes else {
                POSIXFileSystem.removeFile(at: stagedBackup)
                return "the previous version did not survive staging"
            }
        } catch {
            POSIXFileSystem.removeFile(at: stagedBackup)
            return "the previous version could not be preserved: \(describe(error))"
        }

        rotateBackups(for: path)

        // The newest slot must be a free path: a rename onto a directory fails
        // rather than moving the backup inside it, which is what makes an
        // unusable slot a reported failure instead of a silent misplacement.
        do {
            try POSIXFileSystem.replaceFile(at: "\(path).bak1", with: stagedBackup)
        } catch {
            POSIXFileSystem.removeFile(at: stagedBackup)
            return "the previous version could not be filed: \(describe(error))"
        }
        return nil
    }

    /// Shifts the backup slots down by one, dropping the oldest.
    ///
    /// A slot that cannot be moved is left where it is, and the publication then
    /// fails when the newest slot turns out to be occupied.
    private func rotateBackups(for path: String) {
        POSIXFileSystem.removeFile(at: "\(path).bak\(backupDepth)")
        for depth in stride(from: backupDepth - 1, through: 1, by: -1) {
            let from = "\(path).bak\(depth)"
            guard fileManager.fileExists(atPath: from) else { continue }
            let to = "\(path).bak\(depth + 1)"
            POSIXFileSystem.removeFile(at: to)
            try? POSIXFileSystem.replaceFile(at: to, with: from)
        }
    }

    /// Stages the new bytes and renames them over the target.
    private func stageAndReplace(_ bytes: [UInt8], path: String) -> String? {
        let staged = "\(path).tmp-\(UUID().uuidString)"
        do {
            try POSIXFileSystem.writeFile(bytes, to: staged)
            let written = try POSIXFileSystem.readFile(at: staged)
            guard written == bytes else {
                POSIXFileSystem.removeFile(at: staged)
                return "the staged file did not match the generated bytes"
            }
            try POSIXFileSystem.replaceFile(at: path, with: staged)
        } catch {
            POSIXFileSystem.removeFile(at: staged)
            return "the file could not be replaced: \(describe(error))"
        }
        return nil
    }

    /// Removes sibling temporary files an interrupted run left behind.
    private func removeOrphanTemps(for path: String) {
        let target = URL(fileURLWithPath: path)
        let directory = target.deletingLastPathComponent()
        let name = target.lastPathComponent
        guard
            let entries = try? fileManager.contentsOfDirectory(atPath: directory.path)
        else { return }

        for entry in entries where entry.hasPrefix("\(name).tmp-") || entry.hasPrefix("\(name).bak-tmp-") {
            POSIXFileSystem.removeFile(at: directory.appendingPathComponent(entry).path)
        }
    }

    /// A one-line description of a file error.
    private func describe(_ error: any Error) -> String {
        if let fileError = error as? POSIXFileError {
            return fileError.message
        }
        return String(describing: error)
    }
}
